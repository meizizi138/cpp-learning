#include <iostream>
#include <string>
#include <map>              // map 住在这里
using namespace std;

// w06_p3 词频统计
//
// 【为什么这题难】
// 它一次引入了三个新东西，而这三个本来是第 10 周（STL）的内容：
//   1. map<string, int>     —— 用"单词"当下标的容器
//   2. while (cin >> word)  —— 读"个数未知"的数据
//   3. auto&                —— range-for 遍历容器
// 看懂这个程序，你就提前摸到了第 10 周的门。

int main() {
    // ================================================================
    // ① map：一个"键 -> 值"的容器
    // ================================================================
    // 回顾你写过的字符统计：
    //     int count[26] = {0};
    //     count[s[i] - 'a']++;        <- 用"字符减 'a'"算出 0~25 的下标
    //
    // 那个办法的限制：下标必须是 0~N 的整数。
    // 现在键是【单词】（字符串），根本没法算成整数。
    //
    // map 就是解决这个的：直接用任意类型当"下标"。
    map<string, int> count;
    //  ↑键类型   ↑值类型      ↑变量名

    // ================================================================
    // ② while (cin >> word)：读到"没有数据了"就停
    // ================================================================
    // 题目说"个数未知"，那怎么知道读几个？
    //   答案：一直读到【输入结束】为止。
    //
    // cin >> word 这个表达式有两个作用：
    //   - 有数据可读时：把数据读进来，返回"真"
    //   - 没数据可读时（读到末尾）：返回"假"
    // 所以它能直接当 while 的条件 —— 读到没数据，循环自动结束。
    string word;
    while (cin >> word) {
        // cin >> 会自动跳过空格和换行，所以"空格分隔"和"换行分隔"都能读
        count[word]++;
        // ↑ 这一行的行为很省事：
        //   - 如果 word 还不存在：自动创建，初值 0，然后 +1 -> 变成 1
        //   - 如果 word 已存在：直接 +1
        //   不用像数组那样手动初始化！
    }

    // ================================================================
    // ③ 遍历 map，找最大次数
    // ================================================================
    // 遍历 map 的固定写法：
    //     for (auto& kv : count)
    //         kv.first   是键（单词）
    //         kv.second  是值（次数）
    //
    // auto 让编译器自己推断类型（map 里每个元素的类型很长，写全很啰嗦）
    // &   表示引用 —— 避免复制（这里只读，加不加都行）
    int maxCount = 0;
    for (auto& kv : count) {
        if (kv.second > maxCount) {
            maxCount = kv.second;       // 记下最大次数
        }
    }

    // ================================================================
    // ④ 输出所有出现次数 == maxCount 的单词
    // ================================================================
    // 题目要求"多个答案按字典序输出"。
    // 好消息：map 内部【自动按键排序】—— 遍历时就是字典序。
    //         所以直接遍历输出就行，不用自己排序！
    for (auto& kv : count) {
        if (kv.second == maxCount) {
            cout << kv.first << " " << kv.second << endl;
        }
    }

    return 0;
}
